export function getChartPoints(basePrice = 210, range = "1D") {
  const labels = rangeLabels[range] || rangeLabels["1D"];
  const moves = rangeMoves[range] || rangeMoves["1D"];
  return labels.map((time, index) => {
    const wave = Math.sin(index * 1.7) * (range === "1D" ? 2.8 : 5.5);
    const price = Math.max(1, basePrice + moves[index] + wave);
    return {
      time,
      price: Number(price.toFixed(2)),
      open: Number((price - 1.7).toFixed(2)),
      high: Number((price + 3.6).toFixed(2)),
      low: Number((price - 4.1).toFixed(2)),
      close: Number((price + 1.2).toFixed(2)),
      volume: 20 + index * 4 + Math.round(Math.abs(wave) * 4)
    };
  });
}

